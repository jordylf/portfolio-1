function toSlugRoute(slug) {
  return `#/works/${slug}`;
}

function fromHash() {
  return window.location.hash.replace(/^#\/?/, "");
}

function getWorkBySlug(slug) {
  return works.find((work) => work.slug === slug);
}

function extractYouTubeId(url) {
  try {
    const parsed = new URL(url);
    if (parsed.hostname.includes("youtu.be")) {
      return parsed.pathname.slice(1);
    }
    if (parsed.pathname.startsWith("/embed/")) {
      return parsed.pathname.split("/embed/")[1].split("/")[0];
    }
    if (parsed.pathname.startsWith("/shorts/")) {
      return parsed.pathname.split("/shorts/")[1].split("/")[0];
    }
    return parsed.searchParams.get("v");
  } catch (error) {
    return null;
  }
}

function extractTikTokId(url) {
  const match = url.match(/\/video\/(\d+)/);
  return match ? match[1] : null;
}

function normalizeInstagramEmbed(url) {
  try {
    const parsed = new URL(url);
    const parts = parsed.pathname.split("/").filter(Boolean);
    const contentTypes = ["reel", "p", "tv"];
    const typeIndex = parts.findIndex((part) => contentTypes.includes(part));

    if (typeIndex !== -1 && parts[typeIndex + 1]) {
      return `https://www.instagram.com/${parts[typeIndex]}/${parts[typeIndex + 1]}/embed/captioned/`;
    }

    const trimmed = url.endsWith("/") ? url : `${url}/`;
    return `${trimmed}embed/captioned/`;
  } catch (error) {
    const trimmed = url.endsWith("/") ? url : `${url}/`;
    return `${trimmed}embed/captioned/`;
  }
}

function ensureTikTokEmbedScript() {
  if (document.querySelector('script[data-tiktok-embed-script="true"]')) {
    if (window.tiktokEmbedLoad) {
      window.tiktokEmbedLoad();
    }
    return;
  }

  const script = document.createElement("script");
  script.src = "https://www.tiktok.com/embed.js";
  script.async = true;
  script.dataset.tiktokEmbedScript = "true";
  script.onload = () => {
    if (window.tiktokEmbedLoad) {
      window.tiktokEmbedLoad();
    }
  };
  document.body.append(script);
}

function getEmbedPreviewSrc(item) {
  if (item.type === "video") {
    return item.src;
  }

  if (item.type === "youtube") {
    const videoId = extractYouTubeId(item.src);
    return videoId
      ? `https://www.youtube-nocookie.com/embed/${videoId}?rel=0`
      : null;
  }

  if (item.type === "tiktok") {
    const videoId = extractTikTokId(item.src);
    return videoId ? `https://www.tiktok.com/embed/v2/${videoId}` : null;
  }

  if (item.type === "instagram") {
    return normalizeInstagramEmbed(item.src);
  }

  return null;
}

function isPortraitMedia(item) {
  if (item.type === "tiktok" || item.type === "instagram") {
    return true;
  }

  if (item.type === "youtube") {
    try {
      const parsed = new URL(item.src);
      return parsed.pathname.startsWith("/shorts/");
    } catch (error) {
      return false;
    }
  }

  return false;
}

function createMediaPreview(item) {
  const preview = document.createElement("div");
  preview.className = "media-preview";

  if (item.type === "tiktok-blockquote") {
    const fallback = document.createElement("div");
    fallback.className = "media-preview-fallback";
    fallback.innerHTML = `<span>${item.title}<br>TikTok embed</span>`;
    preview.append(fallback);
    return preview;
  }

  if (item.type === "video") {
    const video = document.createElement("video");
    video.src = encodeURI(item.src);
    video.muted = true;
    video.loop = true;
    video.autoplay = true;
    video.playsInline = true;
    video.preload = "metadata";
    video.setAttribute("aria-hidden", "true");
    preview.append(video);
    video.play().catch(() => { });
    return preview;
  }

  if (item.type === "image") {
    const image = document.createElement("img");
    image.src = item.src;
    image.alt = item.title;
    image.loading = "lazy";
    preview.append(image);
    return preview;
  }

  const embedSrc = getEmbedPreviewSrc(item);

  if (embedSrc) {
    const frame = document.createElement("iframe");
    frame.src = embedSrc;
    frame.loading = "lazy";
    frame.allow =
      "accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share";
    frame.referrerPolicy = "strict-origin-when-cross-origin";
    frame.allowFullscreen = true;
    frame.title = item.title;
    preview.append(frame);
    return preview;
  }

  const fallback = document.createElement("div");
  fallback.className = "media-preview-fallback";
  fallback.innerHTML = `<span>${item.title}</span>`;
  preview.append(fallback);
  return preview;
}

function buildModalContent(item) {
  modalBody.innerHTML = "";

  if (item.type === "tiktok-blockquote") {
    const wrapper = document.createElement("div");
    wrapper.className = "modal-media-wrap";

    const embedContainer = document.createElement("div");
    embedContainer.className = "modal-tiktok-embed";
    embedContainer.innerHTML = item.embedHtml;
    wrapper.append(embedContainer);

    const link = document.createElement("a");
    link.href = item.src;
    link.target = "_blank";
    link.rel = "noreferrer";
    link.className = "modal-source-link";
    link.textContent = "Open original";
    wrapper.append(link);

    modalBody.append(wrapper);
    ensureTikTokEmbedScript();
    return;
  }

  if (item.type === "video") {
    const wrapper = document.createElement("div");
    wrapper.className = "modal-media-wrap";

    const video = document.createElement("video");
    video.className = "modal-embed";
    video.src = encodeURI(item.src);
    video.controls = true;
    video.autoplay = true;
    video.loop = true;
    video.playsInline = true;
    video.volume = 0.5;
    video.addEventListener("loadedmetadata", () => {
      const isPortrait = video.videoHeight > video.videoWidth;
      wrapper.classList.toggle("is-portrait-media", isPortrait);
    });
    wrapper.append(video);

    const link = document.createElement("a");
    link.href = item.sourceHref || encodeURI(item.src);
    link.target = "_blank";
    link.rel = "noreferrer";
    link.className = "modal-source-link";
    link.textContent = "Open original";
    wrapper.append(link);

    modalBody.append(wrapper);
    video.play().catch(() => { });
    return;
  }

  if (item.type === "image") {
    const image = document.createElement("img");
    image.className = "modal-image";
    image.src = item.src;
    image.alt = item.title;
    modalBody.append(image);
    return;
  }

  const embedSrc = getEmbedPreviewSrc(item);

  if (!embedSrc) {
    const fallback = document.createElement("div");
    fallback.className = "media-preview-fallback";
    fallback.textContent = "Media link needs to be updated.";
    modalBody.append(fallback);
    return;
  }

  const wrapper = document.createElement("div");
  wrapper.className = "modal-media-wrap";
  wrapper.classList.toggle("is-portrait-media", isPortraitMedia(item));

  const frame = document.createElement("iframe");
  frame.className = "modal-embed";
  frame.src = embedSrc;
  frame.allow =
    "accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share";
  frame.referrerPolicy = "strict-origin-when-cross-origin";
  frame.allowFullscreen = true;
  frame.title = item.title;
  wrapper.append(frame);

  const link = document.createElement("a");
  link.href = item.src;
  link.target = "_blank";
  link.rel = "noreferrer";
  link.className = "modal-source-link";
  link.textContent = "Open original";
  wrapper.append(link);

  modalBody.append(wrapper);
}

function openModal(item) {
  buildModalContent(item);
  document.body.classList.add("modal-open");
  if (!modal.open) {
    modal.showModal();
  }
}

function closeModal() {
  if (modal.open) {
    modal.close();
  }
  modalBody.innerHTML = "";
  document.body.classList.remove("modal-open");
}

function renderMediaCards(media) {
  mediaGrid.innerHTML = "";

  media.forEach((item) => {
    const card = document.createElement("article");
    card.className = "media-card";
    card.tabIndex = 0;
    card.setAttribute("role", "button");
    card.setAttribute("aria-label", `Open ${item.title}`);
    card.style.setProperty(
      "--card-gradient",
      "linear-gradient(180deg, rgba(255, 255, 255, 0.06), transparent 55%)"
    );

    const content = document.createElement("div");
    content.className = "media-card-content";
    content.append(createMediaPreview(item));

    const meta = document.createElement("div");
    meta.className = "media-meta";
    meta.innerHTML = `
      <div class="media-meta-left">
        <span class="media-title">${item.title}</span>
        <span class="media-type">${item.type}</span>
      </div>
      <span class="play-chip">${item.type === "image" ? "VIEW" : "OPEN"}</span>
    `;

    content.append(meta);
    card.append(content);
    card.addEventListener("click", () => openModal(item));
    card.addEventListener("keydown", (event) => {
      if (event.key === "Enter" || event.key === " ") {
        event.preventDefault();
        openModal(item);
      }
    });

    mediaGrid.append(card);
  });
}

