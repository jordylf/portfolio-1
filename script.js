    video.className = "feature-card-video";
    video.src = encodeURI(featured.thumbnailVideo);
    video.autoplay = true;
    video.muted = true;
    video.loop = true;
    video.playsInline = true;
    video.preload = "none";
    video.setAttribute("aria-hidden", "true");
