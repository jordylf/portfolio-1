function showHome() {
  homeView.hidden = false;
  worksSection.hidden = false;
  termsSection.hidden = false;
  detailView.hidden = true;
  closeModal();
}

function showDetail(work) {
  homeView.hidden = true;
  worksSection.hidden = true;
  termsSection.hidden = true;
  detailView.hidden = false;
  mediaGrid.classList.toggle("is-centered", work.layout === "centered");

  detailTagline.textContent = work.detailTagline;
  detailTitle.textContent = work.title;
  detailDescription.textContent = work.description;

  renderMediaCards(work.media);
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function syncViewFromHash() {
  const hash = fromHash();
  if (!hash || hash === "/") {
    showHome();
    return;
  }

  const match = hash.match(/^works\/(.+)$/);
  if (!match) {
    showHome();
    return;
  }

  const work = getWorkBySlug(match[1]);
  if (!work) {
    showHome();
    return;
  }

  showDetail(work);
}

renderShowreelFeature();
renderWorksGrid();
syncViewFromHash();

window.addEventListener("hashchange", syncViewFromHash);
